from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from cee.catalog import load_framework  # noqa: E402
from cee.models import THEME_LABELS, THEME_ORDER  # noqa: E402


def main() -> int:
    framework = load_framework()
    automated = [control for control in framework.controls if control.automated]
    manual = [control for control in framework.controls if not control.automated]

    lines = [
        "# Control mapping",
        "",
        f"**Framework:** {framework.name} ({framework.version})  ",
        f"**Source:** {framework.source}  ",
        f"**Controls:** {len(framework.controls)} ({len(automated)} automated, {len(manual)} manual)  ",
        "**Generated by:** `python scripts/generate_mapping.py`",
        "",
        "The YAML catalog at `cee/frameworks/iso27001_2022.yaml` is the source of truth.",
        "A control is automated when at least one check is mapped to it. Everything else",
        "requires manual evidence through `python -m cee attest`.",
        "",
    ]

    for theme in THEME_ORDER:
        subset = [control for control in framework.controls if control.theme == theme]
        if not subset:
            continue
        lines.extend(
            [
                f"## {THEME_LABELS[theme]}",
                "",
                "| Control | Title | Type | Checks | Evidence expectation |",
                "|---|---|---|---|---|",
            ]
        )
        for control in subset:
            checks = ", ".join(f"`{check}`" for check in control.check_ids) or "-"
            evidence_type = "Automated" if control.automated else "Manual"
            expectation = control.evidence_expectation.replace("|", "\\|").replace("\n", " ")
            lines.append(
                f"| {control.id} | {control.title} | {evidence_type} | {checks} | {expectation} |"
            )
        lines.append("")

    output = ROOT / "docs" / "control-mapping.md"
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {output} ({len(framework.controls)} controls)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
